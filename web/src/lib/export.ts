import type { AnalysisResult, CellStatus, Evidence, Finding, Tier } from '@workbench/shared';

export type ExportSection = 'all' | 'overview' | 'comparison' | 'discrepancies' | 'missing' | 'keyValues' | 'perDocument';

export const TIER_LABELS: Record<Tier, string> = {
  extracted: 'Extracted fact',
  derived: 'Derived (rule)',
  interpretation: 'AI interpretation',
};

const CELL_ICONS: Record<CellStatus, string> = { match: '✓', equivalent: '≈', mismatch: '✗', missing: '–', reported: '•' };
const VERIFY_ICONS: Record<Evidence['verification'], string> = { exact: '✓', fuzzy: '~', unverified: '?' };

const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function citation(e: Evidence): string {
  return `[${e.alias} · p${e.pageNo} · ${e.handle}${VERIFY_ICONS[e.verification]}]`;
}

function findingLine(f: Finding, r: AnalysisResult): string {
  const cites = f.evidence
    .map((e) => r.evidence[e.handle])
    .filter((e): e is Evidence => e !== undefined)
    .map(citation)
    .join(' ');
  const sev = f.severity !== 'info' ? ` (${f.severity})` : '';
  const verdict = f.verdict ? ` — AI verdict: ${f.verdict}${f.verdictNote ? `: ${f.verdictNote}` : ''}` : '';
  const scope = f.evidence.length === 0 ? ` [checked: ${f.documentIds.map((id) => r.documents.find((d) => d.id === id)?.alias ?? '?').join(', ')}]` : '';
  return `- **${f.title}**${sev} _${TIER_LABELS[f.tier]}_ — ${f.detail}${verdict} ${cites}${scope}`.trimEnd();
}

function documentsBlock(r: AnalysisResult): string {
  return ['**Documents**', ...r.documents.map((d) => `- ${d.alias}: ${d.name}`)].join('\n');
}

function comparisonTable(r: AnalysisResult): string {
  if (r.comparison.length === 0) return '_No attributes compared._';
  const header = `| Attribute | ${r.documents.map((d) => `${d.alias} ${esc(d.name)}`).join(' | ')} | Status |`;
  const sep = `|---|${r.documents.map(() => '---').join('|')}|---|`;
  const rows = r.comparison.map((row) => {
    const cells = r.documents.map((d) => {
      const c = row.cells.find((x) => x.documentId === d.id);
      if (!c || c.value === null) return '–';
      return `${CELL_ICONS[c.status]} ${esc(c.value)}${c.evidenceHandle ? ` (${c.evidenceHandle})` : ''}`;
    });
    return `| ${esc(row.label)} | ${cells.join(' | ')} | ${row.rowStatus} |`;
  });
  return [header, sep, ...rows].join('\n');
}

function list(findings: Finding[], r: AnalysisResult, empty: string): string {
  return findings.length > 0 ? findings.map((f) => findingLine(f, r)).join('\n') : `_${empty}_`;
}

/** Render a result (or one section of it) as Markdown with source citations. */
export function toMarkdown(r: AnalysisResult, section: ExportSection = 'all', instruction?: string): string {
  const parts: string[] = [];
  const want = (s: ExportSection) => section === 'all' || section === s;

  if (section === 'all') {
    parts.push('# Document analysis');
    if (instruction) parts.push(`> ${instruction}`);
    parts.push(documentsBlock(r));
    parts.push(
      r.meta.comparisonMode === 'side_by_side'
        ? 'Side-by-side comparison of different entities (• reported · – not found). Citations: [document · page · evidence, ✓ verified / ~ fuzzy / ? unverified]'
        : 'Legend: ✓ match · ≈ equivalent · ✗ mismatch · – not found. Citations: [document · page · evidence, ✓ verified / ~ fuzzy / ? unverified]',
    );
  }
  if (want('overview')) parts.push('## Summary', `_${TIER_LABELS.interpretation}_`, r.summary, list(r.summaryPoints, r, 'No summary points.'));
  if (want('comparison')) parts.push('## Comparison', comparisonTable(r));
  if (want('discrepancies')) parts.push('## Discrepancies', list(r.discrepancies, r, 'No discrepancies found.'));
  if (want('missing')) parts.push('## Missing information', list(r.missingInformation, r, 'Nothing missing.'));
  if (want('keyValues')) parts.push('## Key values', list(r.keyValues, r, 'No key values.'));
  if (want('perDocument')) {
    parts.push('## Per document');
    for (const p of r.perDocument) {
      const d = r.documents.find((x) => x.id === p.documentId);
      parts.push(`### ${d?.alias ?? '?'}: ${d?.name ?? ''}`, list(p.findings, r, 'No findings.'));
    }
  }
  if (section === 'all' && r.warnings.length > 0) parts.push('## Warnings', r.warnings.map((w) => `- ${w}`).join('\n'));
  if (section === 'all') parts.push(`---\n_Generated by ${r.meta.provider}${r.meta.model ? ` (${r.meta.model})` : ''}, prompt ${r.meta.promptVersion}._`);
  return parts.join('\n\n');
}

/** JSON export: the requested section plus the evidence it cites (so citations resolve). */
export function toJson(r: AnalysisResult, section: ExportSection = 'all'): string {
  if (section === 'all') return JSON.stringify(r, null, 2);
  const pick: Record<Exclude<ExportSection, 'all'>, unknown> = {
    overview: { summary: r.summary, summaryPoints: r.summaryPoints },
    comparison: r.comparison,
    discrepancies: r.discrepancies,
    missing: r.missingInformation,
    keyValues: r.keyValues,
    perDocument: r.perDocument,
  };
  const data = pick[section];
  const handles = new Set(JSON.stringify(data).match(/"E\d+"/g)?.map((h) => h.slice(1, -1)) ?? []);
  const evidence = Object.fromEntries(Object.entries(r.evidence).filter(([h]) => handles.has(h)));
  return JSON.stringify({ documents: r.documents, [section]: data, evidence }, null, 2);
}

/**
 * Plain-text rendering of the Markdown export: headings become underlined titles and
 * emphasis markers are removed. Tables, citations and tier labels are kept, so the
 * text file carries the same provenance as the copied output.
 */
export function toPlainText(r: AnalysisResult, section: ExportSection = 'all', instruction?: string): string {
  return toMarkdown(r, section, instruction)
    .split('\n')
    .flatMap((line) => {
      const h = /^(#{1,3})\s+(.*)$/.exec(line);
      if (h) {
        const title = h[2]!.trim();
        const rule = h[1]!.length === 1 ? '=' : h[1]!.length === 2 ? '-' : '';
        return rule ? [title.toUpperCase(), rule.repeat(title.length)] : [title];
      }
      if (/^\|(?:---\|)+$/.test(line)) return [line]; // table separator row
      return [
        line
          .replace(/^> /, '')
          .replace(/\*\*(.+?)\*\*/g, '$1')
          .replace(/(^|\s)_(.+?)_(?=\s|$)/g, '$1$2')
          .replace(/\\\|/g, '|')
          .replace(/^---$/, '-'.repeat(60)),
      ];
    })
    .join('\n');
}

/** Build a safe, descriptive file name, e.g. "analysis-discrepancies-2026-11-26.txt". */
export function exportFileName(section: ExportSection, date = new Date()): string {
  return `analysis-${section === 'all' ? 'full' : section}-${date.toISOString().slice(0, 10)}.txt`;
}

/** Trigger a browser download of `text` as a UTF-8 .txt file. */
export function downloadText(text: string, fileName: string): void {
  const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  a.rel = 'noopener';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 0);
}

/** Copy text to the clipboard, falling back to a hidden textarea where the API is unavailable. */
export async function copyText(text: string): Promise<void> {
  if (navigator.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      return;
    } catch {
      /* fall through to legacy path */
    }
  }
  const ta = document.createElement('textarea');
  ta.value = text;
  ta.setAttribute('readonly', '');
  ta.style.position = 'fixed';
  ta.style.opacity = '0';
  document.body.appendChild(ta);
  ta.select();
  const ok = document.execCommand('copy');
  document.body.removeChild(ta);
  if (!ok) throw new Error('Copy failed');
}
