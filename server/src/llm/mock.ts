import type { LlmPlan, LlmSynthesis, PlanAttribute } from '@workbench/shared';
import { deterministicExtract } from '../analysis/deterministic.js';
import type { SynthesisInput } from '../analysis/prompts.js';
import { fallbackPlan } from '../analysis/templates.js';
import type { LoadedDocument } from '../types.js';
import type { GenerateRequest, LlmProvider } from './provider.js';

/**
 * Deterministic stand-in for a language model. It reads the structured `context`
 * of each request (never the prompt text) and produces schema-valid output.
 * Used by the automated tests and for running the app without Ollama.
 */
export class MockProvider implements LlmProvider {
  readonly name = 'mock' as const;
  readonly model = null;

  async generate<T>(req: GenerateRequest<T>): Promise<T> {
    switch (req.stage) {
      case 'plan': {
        const out: LlmPlan = {
          attributes: fallbackPlan().attributes.map(({ key, label, valueType, required }) => ({ key, label, valueType, required })),
        };
        return req.schema.parse(out);
      }
      case 'extract': {
        const ctx = req.context as { attributes: PlanAttribute[]; document: Pick<LoadedDocument, 'chunks' | 'facts'> };
        return req.schema.parse(deterministicExtract(ctx.attributes, ctx.document));
      }
      case 'synthesise': {
        const ctx = req.context as SynthesisInput;
        return req.schema.parse(mockSynthesis(ctx));
      }
    }
  }

  async health(): Promise<boolean> {
    return true;
  }
}

function mockSynthesis(input: SynthesisInput): LlmSynthesis {
  const discrepancies = input.derivedFindings.filter((f) => f.category === 'discrepancy');
  const missing = input.derivedFindings.filter((f) => f.category === 'missing_information');
  const high = discrepancies.filter((f) => f.severity === 'high').length;
  const summary = [
    `Reviewed ${input.documents.length} document(s) (${input.documents.map((d) => d.alias).join(', ')}) for: "${input.instruction}".`,
    discrepancies.length > 0
      ? `Found ${discrepancies.length} discrepancy(ies), ${high} of high severity.`
      : 'No discrepancies were detected between the documents.',
    missing.length > 0 ? `${missing.length} item(s) of information are missing or blank.` : '',
    '(Generated by the offline mock provider.)',
  ]
    .filter(Boolean)
    .join(' ');
  return {
    summary,
    summaryPoints: discrepancies
      .filter((f) => f.evidence.length > 0)
      .slice(0, 5)
      .map((f) => ({ title: f.title, detail: f.detail, evidence: f.evidence })),
    assessments: input.derivedFindings.map((f) => ({ findingId: f.id, verdict: 'confirmed' as const, explanation: 'Confirmed by rule.' })),
    additionalFindings: [],
  };
}
